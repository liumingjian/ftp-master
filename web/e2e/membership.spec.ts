import { openManagementPage } from './explorer'
import { expect, test } from '@playwright/test'
import { ADMINISTRATOR_PASSWORD, ADMINISTRATOR_USERNAME, signIn } from './signin'

test('Administrator browses and reshapes the organization hierarchy and selects group members by name', async ({ page }) => {
  await page.goto('/sign-in')
  await signIn(page, ADMINISTRATOR_USERNAME, ADMINISTRATOR_PASSWORD)
  await openManagementPage(page, '组织与用户组管理')
  const panel = page.getByRole('region', { name: '组织与用户组管理' })
  const suffix = Date.now().toString()
  const parent = `Engineering-${suffix}`
  const child = `Platform-${suffix}`
  const create = panel.getByRole('button', { name: '新建组织', exact: true })
  const organization = page.getByRole('dialog')
  await create.click()
  await organization.getByLabel('组织名称').fill(parent)
  await organization.getByRole('button', { name: '保存组织' }).click()
  await expect(panel.getByRole('row').filter({ hasText: parent })).toBeVisible()

  await create.click()
  await organization.getByLabel('组织名称').fill(child)
  const parentSelect = organization.getByRole('combobox', { name: '上级组织', exact: true })
  await parentSelect.selectOption({ label: parent })
  await organization.getByRole('button', { name: '保存组织' }).click()
  await expect(panel.getByRole('row').filter({ hasText: child })).toContainText(parent)
  await panel.getByRole('button', { name: '编辑组织 ' + parent, exact: true }).click()
  await expect(parentSelect.getByRole('option', { name: new RegExp(child) })).toHaveCount(0)
  await page.keyboard.press('Escape')
  await panel.getByRole('button', { name: '编辑组织 ' + child, exact: true }).click()
  await parentSelect.selectOption('')
  const renamed = `Infrastructure-${suffix}`
  await organization.getByLabel('组织名称').fill(renamed)
  await organization.getByRole('button', { name: '保存组织' }).click()
  await expect(panel.getByRole('row').filter({ hasText: renamed }).getByRole('cell', { name: '—' })).toBeVisible()
  await panel.getByRole('button', { name: '编辑组织 ' + parent, exact: true }).click()
  await organization.getByRole('button', { name: '删除组织' }).click()
  await organization.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(panel.getByRole('row').filter({ hasText: parent })).toHaveCount(0)

  const project = `Project-${suffix}`
  await panel.getByRole('button', { name: '用户组', exact: true }).click()
  await panel.getByRole('button', { name: '新建用户组', exact: true }).click()
  await page.getByRole('dialog').getByLabel('用户组名称').fill(project)
  await page.getByRole('dialog').getByRole('button', { name: '创建用户组', exact: true }).click()
  await panel.getByRole('searchbox', { name: '搜索用户组' }).fill(project)
  const edit = panel.getByRole('button', { name: '管理成员 ' + project, exact: true })
  await edit.click()
  const members = page.getByRole('dialog', { name: project })
  await members.getByRole('searchbox', { name: '搜索成员姓名或用户名' }).fill(ADMINISTRATOR_USERNAME)
  await members.getByRole('button', { name: '添加 ' + ADMINISTRATOR_USERNAME, exact: true }).click()
  await members.getByRole('button', { name: '保存成员' }).click()
  await expect(panel.getByRole('row').filter({ hasText: project })).toContainText('1 位')
  await edit.click()
  await members.getByRole('button', { name: '移除 ' + ADMINISTRATOR_USERNAME, exact: true }).click()
  await members.getByRole('button', { name: '保存成员' }).click()
  await expect(panel.getByRole('row').filter({ hasText: project })).toContainText('0 位')
})

test('Administrator moves a User and sees the current Organization immediately', async ({ page }) => {
  await page.goto('/sign-in')
  await signIn(page, ADMINISTRATOR_USERNAME, ADMINISTRATOR_PASSWORD)
  await openManagementPage(page, '组织与用户组管理')
  const panel = page.getByRole('region', { name: '组织与用户组管理' })
  const target = `Lifecycle-${Date.now()}`
  await panel.getByRole('button', { name: '新建组织', exact: true }).click()
  await page.getByRole('dialog').getByLabel('组织名称').fill(target)
  await page.getByRole('dialog').getByRole('button', { name: '保存组织' }).click()
  await expect(panel.getByRole('row').filter({ hasText: target })).toBeVisible()
  const session = await (await page.request.get('/api/session')).json()
  const manage = panel.getByRole('button', { name: '管理用户 ' + ADMINISTRATOR_USERNAME, exact: true })
  const edit = page.getByRole('dialog', { name: '管理用户' })
  await panel.getByRole('button', { name: '用户', exact: true }).click()
  await panel.getByRole('searchbox', { name: '搜索姓名、用户名或组织' }).fill(ADMINISTRATOR_USERNAME)
  await manage.click()
  await edit.getByLabel('用户所属组织').selectOption({ label: target })
  const changed = page.waitForResponse(r => r.url().endsWith(`/users/${session.id}/organization`) && r.request().method() === 'PUT')
  await edit.getByRole('button', { name: '保存变更', exact: true }).click()
  expect((await changed).status()).toBe(204)
  await expect(panel.getByRole('row').filter({
    has: page.getByRole('button', { name: '管理用户 ' + ADMINISTRATOR_USERNAME, exact: true }),
  })).toContainText(target)
  const organizations = await (await page.request.get('/api/organizations')).json()
  const organization = organizations.find((o: { name: string }) => o.name === target)
  await expect.poll(async () => (await (await page.request.get('/api/session')).json()).organizationId).toBe(organization.id)
  await page.reload()
  await panel.getByRole('button', { name: '用户', exact: true }).click()
  await manage.click()
  await expect(edit.getByLabel('用户所属组织')).toHaveValue(String(organization.id))
})
